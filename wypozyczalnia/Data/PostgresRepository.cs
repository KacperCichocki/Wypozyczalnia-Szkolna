using Npgsql;
using wypozyczalnia.Models;

namespace Wypozyczalnia.Data;

/// <summary>PostgreSQL persistence for equipment and the rental event history.</summary>
public sealed class PostgresRepository
{
    private readonly string connectionString;

    public PostgresRepository(string? configuredConnectionString = null)
    {
        connectionString = configuredConnectionString
            ?? Environment.GetEnvironmentVariable("SCHOOL_RENTAL_DB")
            ?? throw new InvalidOperationException(
                "Ustaw zmienną środowiskową SCHOOL_RENTAL_DB na ciąg połączenia PostgreSQL.");
    }

    public void Initialize()
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var command = new NpgsqlCommand("""
            CREATE TABLE IF NOT EXISTS equipment (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name text NOT NULL,
                category text NOT NULL,
                description text NOT NULL DEFAULT '',
                serial_number text NOT NULL UNIQUE,
                technical_condition text NOT NULL DEFAULT 'Dobry',
                is_available boolean NOT NULL DEFAULT true,
                borrower text NULL
            );
            CREATE TABLE IF NOT EXISTS rental_history (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                occurred_at timestamp with time zone NOT NULL,
                equipment_id integer NULL REFERENCES equipment(id) ON DELETE SET NULL,
                equipment_name text NOT NULL,
                serial_number text NOT NULL,
                person text NOT NULL,
                action text NOT NULL CHECK (action IN ('Wypożyczenie', 'Zwrot'))
            );
            """, connection);
        command.ExecuteNonQuery();

        using var count = new NpgsqlCommand("SELECT COUNT(*) FROM equipment", connection);
        if (Convert.ToInt64(count.ExecuteScalar()) == 0)
        {
            using var seed = new NpgsqlCommand("""
                INSERT INTO equipment (name, category, description, serial_number, technical_condition, is_available)
                VALUES
                  ('Laptop Dell', 'Elektronika', 'Laptop do nauki programowania', 'EL-001', 'Dobry', true),
                  ('Projektor Epson', 'Elektronika', 'Projektor do prezentacji', 'EL-002', 'Dobry', true),
                  ('Mikroskop', 'Biologia', 'Mikroskop do zajęć laboratoryjnych', 'BI-001', 'Dobry', false),
                  ('Kalkulator naukowy', 'Matematyka', 'Kalkulator do obliczeń matematycznych', 'MA-001', 'Dobry', true)
                ON CONFLICT (serial_number) DO NOTHING;
                """, connection);
            seed.ExecuteNonQuery();
        }
    }

    public List<Sprzet> GetEquipment()
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var command = new NpgsqlCommand("""
            SELECT id, name, category, description, serial_number, technical_condition, is_available, borrower
            FROM equipment ORDER BY id
            """, connection);
        using var reader = command.ExecuteReader();
        var items = new List<Sprzet>();
        while (reader.Read())
        {
            items.Add(new Sprzet
            {
                Id = reader.GetInt32(0), Nazwa = reader.GetString(1), Kategoria = reader.GetString(2),
                Opis = reader.GetString(3), NumerSeryjny = reader.GetString(4),
                StanTechniczny = reader.GetString(5), CzyDostepny = reader.GetBoolean(6),
                OsobaWypozyczajaca = reader.IsDBNull(7) ? null : reader.GetString(7)
            });
        }
        return items;
    }

    public List<HistoriaWpisu> GetHistory()
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var command = new NpgsqlCommand("""
            SELECT occurred_at, equipment_name, serial_number, person, action
            FROM rental_history ORDER BY occurred_at DESC, id DESC
            """, connection);
        using var reader = command.ExecuteReader();
        var items = new List<HistoriaWpisu>();
        while (reader.Read())
            items.Add(new HistoriaWpisu
            {
                Data = reader.GetDateTime(0), NazwaSprzetu = reader.GetString(1),
                NumerSeryjny = reader.GetString(2), Osoba = reader.GetString(3), TypAkcji = reader.GetString(4)
            });
        return items;
    }

    public void Borrow(IEnumerable<Sprzet> equipment, string person)
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var transaction = connection.BeginTransaction();
        foreach (var item in equipment)
        {
            using var update = new NpgsqlCommand(
                "UPDATE equipment SET is_available = false, borrower = @person WHERE id = @id AND is_available = true",
                connection, transaction);
            update.Parameters.AddWithValue("person", person);
            update.Parameters.AddWithValue("id", item.Id);
            if (update.ExecuteNonQuery() != 1)
                throw new InvalidOperationException($"Sprzęt {item.NumerSeryjny} nie jest już dostępny.");
            AddHistory(connection, transaction, item, person, "Wypożyczenie");
        }
        transaction.Commit();
    }

    public void Return(IEnumerable<Sprzet> equipment)
    {
        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var transaction = connection.BeginTransaction();
        foreach (var item in equipment)
        {
            using var update = new NpgsqlCommand(
                "UPDATE equipment SET is_available = true, borrower = NULL WHERE id = @id AND is_available = false",
                connection, transaction);
            update.Parameters.AddWithValue("id", item.Id);
            // RETURNING borrower returns NULL after the update, so keep the name from the loaded model.
            if (update.ExecuteNonQuery() != 1)
                throw new InvalidOperationException($"Sprzęt {item.NumerSeryjny} nie jest wypożyczony.");
            AddHistory(connection, transaction, item, item.OsobaWypozyczajaca ?? "Nieznana osoba", "Zwrot");
        }
        transaction.Commit();
    }

    private static void AddHistory(NpgsqlConnection connection, NpgsqlTransaction transaction,
        Sprzet item, string person, string action)
    {
        using var command = new NpgsqlCommand("""
            INSERT INTO rental_history (occurred_at, equipment_id, equipment_name, serial_number, person, action)
            VALUES (@date, @equipmentId, @name, @serial, @person, @action)
            """, connection, transaction);
        command.Parameters.AddWithValue("date", DateTime.UtcNow);
        command.Parameters.AddWithValue("equipmentId", item.Id);
        command.Parameters.AddWithValue("name", item.Nazwa);
        command.Parameters.AddWithValue("serial", item.NumerSeryjny);
        command.Parameters.AddWithValue("person", person);
        command.Parameters.AddWithValue("action", action);
        command.ExecuteNonQuery();
    }
}
